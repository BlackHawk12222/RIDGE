"""Pack the .py files in this folder into frozen_content.c (MicroPython frozen
string modules). Run after changing any .py here:  python3 make_frozen.py

These are the pure-Python parts of modules VEXcode V5 Python has built in
(asyncio/uasyncio). They compile on first import, then live in RAM.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(HERE), "frozen_content.c")


def main():
    files = []
    for root, dirs, names in os.walk(HERE):
        dirs.sort()
        for n in sorted(names):
            if n.endswith(".py") and n != "make_frozen.py":
                full = os.path.join(root, n)
                files.append((os.path.relpath(full, HERE).replace(os.sep, "/"), full))
    names, sizes, content = [], [], bytearray()
    for rel, full in files:
        data = open(full, "rb").read().replace(b"\r\n", b"\n")
        names.append(rel)
        sizes.append(len(data))
        content += data + b"\0"
    with open(OUT, "w", newline="\n") as f:
        f.write("// Generated by frozen/make_frozen.py. Do not edit.\n")
        f.write('#include <stdint.h>\n#include "py/mpconfig.h"\n#if MICROPY_MODULE_FROZEN_STR\n\n')
        f.write("const char mp_frozen_names[] = {\n")
        for n in names:
            f.write('    "%s\\0"\n' % n)
        f.write('    "\\0"\n};\n\n')
        f.write("const uint32_t mp_frozen_str_sizes[] = { %s, 0 };\n\n" % ", ".join(map(str, sizes)))
        f.write("const char mp_frozen_str_content[] = {\n")
        for i in range(0, len(content), 20):
            f.write("    " + ",".join(str(b) for b in content[i:i + 20]) + ",\n")
        f.write("};\n\n#endif\n")
    print("wrote %s: %s" % (OUT, ", ".join(names)))


main()
